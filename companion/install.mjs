#!/usr/bin/env node
/**
 * Registers the StreamHunter Companion with Google Chrome (native messaging, current user only).
 *
 *   node install.mjs --extension-id <id>            install (the ID is shown in StreamHunter → Settings → Companion)
 *   node install.mjs --uninstall                    remove the registration (the work folder is kept)
 *
 * Options for testing: --chrome-dir <Chrome user data folder>, --home <work folder>.
 * Writes: <Chrome>/NativeMessagingHosts/com.streamhunter.companion.json, <work>/bin/streamhunter-companion,
 * <work>/config.json. Nothing else is changed.
 */
import { chmodSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ensureLayout, workDir } from "./src/paths.mjs";
import { detectTools } from "./src/tools.mjs";

export const HOST_NAME = "com.streamhunter.companion";
const EXT_ID = /^[a-p]{32}$/;

const q = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

export function hostManifest(launcher, extensionId) {
  return { name: HOST_NAME, description: "StreamHunter Companion (local video tools)", path: launcher, type: "stdio", allowed_origins: [`chrome-extension://${extensionId}/`] };
}

export function launcherScript({ node, main, home }) {
  return `#!/bin/sh\n# Started by Chrome for StreamHunter. Generated by install.mjs.\nexport SH_COMPANION_HOME=${q(home)}\nexec ${q(node)} ${q(main)} "$@"\n`;
}

export function install({ extensionId, chromeDir, home, node = process.execPath, main = resolve(dirname(fileURLToPath(import.meta.url)), "src", "main.mjs") }) {
  if (!EXT_ID.test(extensionId ?? "")) throw new Error("Give the extension ID shown in StreamHunter → Settings → Companion (32 letters a–p).");
  ensureLayout(home);
  const launcher = join(home, "bin", "streamhunter-companion");
  writeFileSync(launcher, launcherScript({ node, main, home }));
  chmodSync(launcher, 0o755);
  writeFileSync(join(home, "config.json"), JSON.stringify({ allowed_origins: [`chrome-extension://${extensionId}/`], installed_at: new Date().toISOString(), node, main }, null, 2));
  const hosts = join(chromeDir, "NativeMessagingHosts");
  mkdirSync(hosts, { recursive: true });
  const manifest = join(hosts, `${HOST_NAME}.json`);
  writeFileSync(manifest, JSON.stringify(hostManifest(launcher, extensionId), null, 2));
  return { manifest, launcher };
}

export function uninstall({ chromeDir }) {
  const manifest = join(chromeDir, "NativeMessagingHosts", `${HOST_NAME}.json`);
  const existed = existsSync(manifest);
  rmSync(manifest, { force: true });
  return { manifest, existed };
}

function arg(name) {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const chromeDir = resolve(arg("--chrome-dir") ?? join(homedir(), "Library", "Application Support", "Google", "Chrome"));
  const home = resolve(arg("--home") ?? workDir());
  try {
    if (process.argv.includes("--uninstall")) {
      const r = uninstall({ chromeDir });
      console.log(r.existed ? `Removed ${r.manifest}` : "Nothing to remove.");
    } else {
      if (Number(process.versions.node.split(".")[0]) < 22) throw new Error(`Node 22 or later is required (this is ${process.version}).`);
      const r = install({ extensionId: arg("--extension-id"), chromeDir, home });
      console.log(`Registered with Chrome: ${r.manifest}\nLauncher: ${r.launcher}\nWork folder: ${home}\n`);
      const tools = await detectTools();
      for (const t of Object.values(tools)) console.log(`${t.ok ? "✓" : "✗"} ${t.name.padEnd(8)} ${t.version ?? "—"}  ${t.ok ? "" : `${t.detail} (needs ${t.min} for ${t.why})`}`);
      console.log("\nReload StreamHunter → Settings → Companion → Check again.");
    }
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
